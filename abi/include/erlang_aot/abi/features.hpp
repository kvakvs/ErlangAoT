// Unknown IDs are invalid inputs, never an invented future feature or a successful fallback.
constexpr const FeatureInfo *find_feature(FeatureId id) noexcept {
    for (const auto &feature : feature_catalog) {
        if (feature.id == id) {
            return &feature;
        }
    }
    return nullptr;
}
